#!/usr/bin/env node
// copy-extract (UI1-11, DEC-25): the copy deck. Extracts every user-facing clinical copy source into copy/*.json and the
// inventory, so wording is machine-checkable against the approval records (approvals/copy.json, approvals/<slug>.json):
//   copy/protein-messages.json, copy/diabetes-messages.json   flattened MESSAGES objects (key → text)
//   copy/templates.json                                        both PHP template files (slug.key → text)
//   copy/inline.json                                           static [data-copy] strings in the two tool pages (key → text)
//   copy/pages.json                                            landing pages + medical disclaimer (only when LLD_WP_URL is set, OI-1)
//   copy/inventory.json                                        every source and every key with its locator
// Usage: node tests/ci/copy-extract.mjs [--check]   (--check: exit 1 if any copy/*.json would change; `make copy-extract`)
// refresh-approvals.mjs writes the same files through deckFiles(), so the two generators cannot drift.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { JSDOM } from 'jsdom';
import { ROOT, TOOL_FILES, ALL_TOOL_FILES, GUARDED_TOOLS, toolPath } from '../lib/paths.mjs';
import { extractCopy, TEMPLATE_FILES } from '../lib/copy.mjs';
import { closeAll } from '../lib/tool-page.mjs';

/** WordPress pages that carry clinical copy (FR1-04 landing pages, FR1-17 disclaimer); extracted when LLD_WP_URL is set. */
export const PAGES = { 'landing.protein': '/health-tools/protein/', 'landing.diabetes': '/health-tools/diabetes/', 'disclaimer': '/medical-disclaimer/' };

/** Static inline copy: elements carrying data-copy in the served HTML (banners built from MESSAGES carry the attribute inside
 *  render templates and are covered by their MESSAGES keys, so only static markup is listed here). */
export function inlineCopy(slug) {
  const doc = new JSDOM(readFileSync(toolPath(slug), 'utf8')).window.document;
  const out = {};
  for (const el of doc.querySelectorAll('[data-copy]')) out[`${slug}.${el.getAttribute('data-copy')}`] = el.textContent.replace(/\s+/g, ' ').trim();
  return out;
}

/** Main-content text of each WordPress page, or {} when no origin is configured (recorded as a pending source). */
export async function pagesCopy(origin = process.env.LLD_WP_URL) {
  if (!origin) return {};
  const out = {};
  for (const [key, path] of Object.entries(PAGES)) {
    const res = await fetch(new URL(path, origin));
    if (!res.ok) throw new Error(`copy-extract: ${path} → ${res.status}`);
    const doc = new JSDOM(await res.text()).window.document;
    const main = doc.querySelector('main, article, #content') || doc.body;
    out[key] = main.textContent.replace(/\s+/g, ' ').trim();
  }
  return out;
}

export async function extractDeck({ pages } = {}) {
  const copy = extractCopy();
  const inline = { ...inlineCopy('protein'), ...inlineCopy('diabetes') };
  const pageText = pages ?? await pagesCopy();
  const inventory = {
    description: 'DEC-25 copy inventory: every user-facing clinical copy source and key, where it lives, and its text hash (approvals/copy.json). Generated by tests/ci/copy-extract.mjs (also refreshed by refresh-approvals.mjs).',
    sources: {
      messages: GUARDED_TOOLS.map((s) => `site/public_html/tools/${ALL_TOOL_FILES[s]}#MESSAGES`),
      templates: Object.values(TEMPLATE_FILES).map((f) => `site/public_html/tools/${f}`),
      inline: ['[data-copy] elements in both tool pages'],
      pages: Object.entries(PAGES).map(([k, p]) => `${k}: ${p} (WordPress; extracted with LLD_WP_URL)`),
    },
    entries: [],
  };
  for (const slug of GUARDED_TOOLS) {
    for (const key of Object.keys(copy.texts.messages[slug])) inventory.entries.push({ key: `messages.${slug}.${key}`, source: `site/public_html/tools/${ALL_TOOL_FILES[slug]}`, locator: `MESSAGES.${key}` });
    for (const key of Object.keys(copy.texts.templates[slug])) inventory.entries.push({ key: `templates.${slug}.${key}`, source: `site/public_html/tools/${TEMPLATE_FILES[slug]}`, locator: key });
  }
  for (const key of Object.keys(inline)) inventory.entries.push({ key: `inline.${key}`, source: `site/public_html/tools/${TOOL_FILES[key.split('.')[0]]}`, locator: `[data-copy="${key.split('.').slice(1).join('.')}"]` });
  for (const key of Object.keys(pageText)) inventory.entries.push({ key: `pages.${key}`, source: PAGES[key], locator: 'main' });
  return { copy, inline, pages: pageText, inventory };
}

/** The copy/*.json files as { relativePath: object }. */
export function deckFiles({ copy, inline, pages, inventory }) {
  return {
    'copy/protein-messages.json': copy.texts.messages.protein,
    'copy/diabetes-messages.json': copy.texts.messages.diabetes,
    'copy/healthy-weight-messages.json': copy.texts.messages['healthy-weight'],
    'copy/templates.json': Object.fromEntries([...Object.entries(copy.texts.templates.protein).map(([k, v]) => [`protein.${k}`, v]), ...Object.entries(copy.texts.templates.diabetes).map(([k, v]) => [`diabetes.${k}`, v])]),
    'copy/inline.json': inline,
    ...(Object.keys(pages).length ? { 'copy/pages.json': pages } : {}),
    'copy/inventory.json': inventory,
  };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const changed = [];
  const deck = await extractDeck();
  for (const [rel, obj] of Object.entries(deckFiles(deck))) {
    const next = JSON.stringify(obj, null, 2) + '\n';
    const cur = (() => { try { return readFileSync(resolve(ROOT, rel), 'utf8'); } catch { return null; } })();
    if (cur === next) continue;
    changed.push(rel);
    if (!check) writeFileSync(resolve(ROOT, rel), next);
  }
  closeAll();
  console.log(changed.length ? `copy-extract ${check ? 'would change' : 'updated'}: ${changed.join(', ')}` : 'copy deck is current');
  process.exit(check && changed.length ? 1 : 0);
}

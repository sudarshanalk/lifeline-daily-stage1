#!/usr/bin/env node
// Homepage v2 calculator card (S2-L1): copies the three signed-off engines, byte for byte, out of the frozen tool pages
// into site/public_html/wp-content/mu-plugins/lld-tools/assets/lld-home-calc.js, so the homepage's quick numbers are the
// engines' own. Nothing is retyped. tests/lead/home-v2-calc.test.mjs fails if the file is not what this script makes.
// Usage: node tools/home-v2/build-home-calc.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const TOOLS = resolve(ROOT, 'site/public_html/tools');
export const OUT = resolve(ROOT, 'site/public_html/wp-content/mu-plugins/lld-tools/assets/lld-home-calc.js');

function slice(src, start, end, file) {
  const a = src.indexOf(start);
  if (a < 0) throw new Error(`${file}: start marker not found: ${start}`);
  const b = src.indexOf(end, a + start.length);
  if (b < 0) throw new Error(`${file}: end marker not found after ${start}: ${end}`);
  return src.slice(a, b + end.length);
}

export function build() {
  const read = (f) => readFileSync(resolve(TOOLS, f), 'utf8').replace(/\r\n/g, '\n');
  const p = read('protein-requirement-tool.html'), d = read('diabetes-risk-tool.html'), h = read('healthy-weight-tool.html');
  const protein = slice(p, 'const BANDS = {', "    sources: [winner.src], interpKey: winner.key, capped, older\n  };\n}", 'protein');
  const diabetes = slice(d, 'var ENGINE = (function(){', '})();', 'diabetes');
  const band = slice(d, 'function bandFor(p){', '}', 'diabetes');
  const hw = slice(h, 'var HW_ENGINE = (function(){', '})();', 'healthy-weight');
  return `/*! lld-home-calc.js — GENERATED by tools/home-v2/build-home-calc.mjs; do not edit.
 *  The signed-off calculator engines, copied unchanged from site/public_html/tools/ (protein v2 DEC-86, QDiabetes-2018
 *  Model A, Healthy Weight Check), for the homepage's quick-check card. CI: tests/lead/home-v2-calc.test.mjs. */
(function (global) {
'use strict';
${protein}

${diabetes}
${band}

${hw}

global.LLD_HOME_CALC = { computeProtein: computeProtein, QDR2018A: ENGINE.QDR2018A, bandFor: bandFor, HW: HW_ENGINE };
})(typeof window !== 'undefined' ? window : globalThis);
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = build();
  if (process.argv.includes('--check')) {
    const cur = readFileSync(OUT, 'utf8');
    if (cur !== out) { console.error('lld-home-calc.js is out of date: run node tools/home-v2/build-home-calc.mjs'); process.exit(1); }
    console.log('lld-home-calc.js matches the tools');
  } else { writeFileSync(OUT, out); console.log('wrote ' + OUT); }
}
